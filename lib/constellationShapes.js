const FACE_EDGES = [
  [0, 2], [1, 3], [2, 4], [3, 5], [4, 6], [5, 6], [2, 7], [3, 8], [7, 8],
];
function face(earL, earR, o = {}) {
  return {
    stars: [
      earL,
      earR,
      o.templeL ?? { x: 0.26, y: 0.4 },
      o.templeR ?? { x: 0.74, y: 0.4 },
      o.eyeL ?? { x: 0.4, y: 0.5 },
      o.eyeR ?? { x: 0.6, y: 0.5 },
      o.nose ?? { x: 0.5, y: 0.6 },
      o.chinL ?? { x: 0.36, y: 0.76 },
      o.chinR ?? { x: 0.64, y: 0.76 },
    ],
    edges: FACE_EDGES,
  };
}

