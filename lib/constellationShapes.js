// key로 완성 상태 모양을 찾는다. 없으면 fallbackShape.
export function getConstellationShape(key) {
  const shape = constellationShapes[key];
  if (!shape) return { size: DEFAULT_SIZE, ...fallbackShape };
  return { size: DEFAULT_SIZE, ...shape };
}
